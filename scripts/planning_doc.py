"""Write docs/07-production-planning.md from planning outputs and the as-is vs reorder-point October runs."""
import json
from pathlib import Path

import catalog as C

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "out"
policy = json.loads((ROOT / "data" / "reorder_policy.json").read_text())
plan = json.loads((OUT / "production_plan.json").read_text())
asis = json.loads((OUT / "simulation_metrics_asis.json").read_text())
tobe = json.loads((OUT / "simulation_metrics_reorder.json").read_text())
name = {c: n for c, n, *_ in C.RAW_MATERIALS}


def inr(x):
    return f"₹{x:,.0f}"


idle_saved = (asis["downtime_cost"] - tobe["downtime_cost"])
premium_saved = asis["local_premium_paid"] - tobe["local_premium_paid"]
L = ["# 7. Production and material planning", "",
     "Phase-2 work after the as-is month exposed sheet stockouts. Generated by `scripts/planning_doc.py`.", "",
     "## Reorder points from actual consumption (`scripts/planning.py`)", "",
     "Reorder point = daily usage × 10 working-day Gujarat lead time + 4 days of safety stock. "
     "Order quantity = 15 working days of usage. Daily usage comes from October's manufacture entries, not guesses. "
     "The levels are written into each item's reorder settings in ERPNext.", "",
     "| Item | Daily usage | Reorder point | Order qty |", "|---|---|---|---|"]
L += [f"| {name.get(c, c)} | {p['daily_usage']} | {p['reorder_point']} | {p['order_qty']} |"
      for c, p in sorted(policy.items(), key=lambda kv: -kv[1]["daily_usage"])]
L += ["", f"The main board's computed reorder point is **{policy['PB-18-PRELAM']['reorder_point']} sheets**. The level first "
      "configured by judgement was 60, which would still have run dry before a Gujarat load arrived.", "",
      "## Policy comparison: the same October, run twice", "",
      "Same orders, same seed. Only the purchasing rule differs.", "",
      "| | As-is: bulk order when retailer payments come in | To-be: joint reorder point, one Gujarat load |",
      "|---|---|---|",
      f"| Idle production (sheet stockouts) | {asis['downtime_days_equiv'] - 0.5:.1f} days, {inr(asis['downtime_cost'] - 13462)} | "
      f"{tobe['downtime_days_equiv'] - 0.5:.1f} days, {inr(tobe['downtime_cost'] - 13462)} |",
      f"| Emergency local buys (8% premium) | {asis['local_emergency_buys']:.0f} ({inr(asis['local_premium_paid'])}) | "
      f"{tobe['local_emergency_buys']:.0f} ({inr(tobe['local_premium_paid'])}), during the switch-over only |",
      f"| Gujarat loads / freight | {asis['bulk_orders']:.0f} / {inr(asis['freight'])} | {tobe['bulk_orders']:.0f} / {inr(tobe['freight'])} |",
      f"| Units delivered | {asis['units_delivered']:.0f} | {tobe['units_delivered']:.0f} |",
      "", f"**About {inr(idle_saved + premium_saved)} a month recovered** (idle salary + emergency premium) with no extra freight. "
      "(The CNC breakdown day is the same in both runs and is excluded above.)", "",
      "A first version of the policy ordered each item separately the moment it crossed its reorder point. That removed the "
      "stockouts but tripled Gujarat loads (10 loads, ₹56,000 freight). Joint replenishment, where any item at its reorder "
      "point triggers one consolidated load at most weekly, keeps freight flat. That trade-off is why the policy is joint.", "",
      "## MRP over the open order book", "",
      f"Production Plan **{plan['plan']}** covers the {len(plan['sales_orders'])} open sales orders taken on 2 Nov "
      f"({len(plan['finished_goods'])} finished-good lines). ERPNext explodes every BOM, nets the requirement against stock in "
      f"each item's store, and raises material requests only for the shortfall: **{', '.join(plan['material_requests'])}**.", "",
      "| Material | Required | In stock | To request |", "|---|---|---|---|"]
L += [f"| {name.get(c, c)} | {v['required']:.1f} | {v['in_stock']:.1f} | {v['to_request']:.1f} |"
      for c, v in sorted(plan["materials"].items(), key=lambda kv: -kv[1]["to_request"]) if v["to_request"] > 0]
L += ["", f"The other {sum(1 for v in plan['materials'].values() if v['to_request'] == 0)} materials are fully covered by stock. "
      "Sheets aren't short this week; screws, locks, channels and edge-band tape are. That's the hardware that also "
      "turned up missing at the October count."]
(ROOT / "docs" / "07-production-planning.md").write_text("\n".join(L) + "\n")
print("\n".join(L[18:32]))
